// Banco: SQLite local (padrão, um computador) ou Postgres/Supabase (vários computadores
// compartilhando a mesma base). O SQL é um só, escrito no que os dois entendem: placeholders `?`
// (convertidos para $1, $2 no Postgres), datas em texto ISO, `on conflict` e `returning`.

import { mkdirSync } from "node:fs";
import { dirname } from "node:path";
import { DatabaseSync } from "node:sqlite";

export type Linha = Record<string, unknown>;

export type Banco = {
  dialeto: "sqlite" | "postgres";
  todos<T = Linha>(sql: string, params?: unknown[]): Promise<T[]>;
  fechar(): Promise<void>;
};

export async function um<T = Linha>(db: Banco, sql: string, params: unknown[] = []): Promise<T | undefined> {
  return (await db.todos<T>(sql, params))[0];
}

export function agora(): string {
  return new Date().toISOString();
}

export function abrirSqlite(arquivo: string): Banco {
  if (arquivo !== ":memory:") mkdirSync(dirname(arquivo), { recursive: true });
  const sqlite = new DatabaseSync(arquivo);
  // WAL deixa o `status` ler enquanto o `rodar` escreve; busy_timeout evita "database is locked".
  sqlite.exec("pragma journal_mode = wal; pragma busy_timeout = 5000; pragma foreign_keys = on;");
  return {
    dialeto: "sqlite",
    async todos<T>(sql: string, params: unknown[] = []) {
      return sqlite.prepare(sql).all(...(params as never[])) as T[];
    },
    async fechar() {
      sqlite.close();
    },
  };
}

export async function abrirPostgres(url: string): Promise<Banco> {
  const { default: postgres } = await import("postgres");
  const host = new URL(url).hostname;
  const local = host === "localhost" || host === "127.0.0.1";
  // prepare: false porque o pooler do Supabase (modo transação) não guarda prepared statements.
  const sql = postgres(url, { prepare: false, ssl: local ? false : "require", max: 3, onnotice: () => undefined });
  return {
    dialeto: "postgres",
    async todos<T>(texto: string, params: unknown[] = []) {
      let n = 0;
      const convertido = texto.replace(/\?/g, () => `$${++n}`);
      return (await sql.unsafe(convertido, params as never[])) as unknown as T[];
    },
    async fechar() {
      await sql.end({ timeout: 5 });
    },
  };
}

/** `DATABASE_URL` preenchida liga o modo compartilhado; vazia usa o SQLite local. */
export async function abrirBanco(databaseUrl: string | undefined, arquivoSqlite: string): Promise<Banco> {
  const db = databaseUrl ? await abrirPostgres(databaseUrl) : abrirSqlite(arquivoSqlite);
  await migrar(db);
  return db;
}

const ID = { sqlite: "integer primary key autoincrement", postgres: "integer generated by default as identity primary key" };

/** Cada item é uma versão. Só se acrescenta no fim; nunca se edita uma versão que já saiu. */
const MIGRACOES: string[] = [
  `
  create table if not exists operadores (
    id {ID}, nome text not null, instagram text not null unique, criado_em text not null, visto_em text not null
  );
  create table if not exists leads (
    id {ID},
    usuario text not null unique,
    origem text not null,
    estado text not null default 'novo',
    nome text, bio text, seguidores integer, seguindo integer, posts integer,
    link_externo text, comercial integer, legendas text,
    pontuacao integer, motivos text,
    dono_de integer,
    abertura text, seguimento text, seguimentos integer not null default 0,
    operador text, contatado_em text, ultimo_envio_em text, respondeu_em text,
    criado_em text not null, atualizado_em text not null
  );
  create index if not exists leads_estado on leads(estado);
  create table if not exists jobs (
    id {ID},
    tipo text not null, lane text not null, payload text not null,
    chave text unique,
    operador text,
    status text not null default 'pendente',
    prioridade integer not null default 0,
    executar_em text not null,
    tentativas integer not null default 0, max_tentativas integer not null default 3,
    travado_por text, travado_em text, ultimo_erro text,
    criado_em text not null, atualizado_em text not null
  );
  create index if not exists jobs_fila on jobs(status, lane, executar_em);
  create table if not exists acoes (id {ID}, operador text not null, tipo text not null, dia text not null, criado_em text not null);
  create index if not exists acoes_dia on acoes(operador, tipo, dia);
  create table if not exists eventos (id {ID}, operador text, tipo text not null, mensagem text not null, lead_id integer, criado_em text not null);
  create table if not exists estado (chave text primary key, valor text not null);
  create table if not exists uso_ia (id {ID}, operador text, dia text not null, entrada integer not null, saida integer not null, custo_usd double precision not null, finalidade text not null, criado_em text not null);
  create table if not exists cache_ia (hash text primary key, resposta text not null, criado_em text not null);
  create table if not exists mensagens (
    id {ID}, lead_id integer not null, operador text,
    externo_id text unique, conversa_id text, contato_id text,
    direcao text not null, texto text not null, status text not null,
    criado_em text not null, atualizado_em text not null
  );
  create index if not exists mensagens_lead on mensagens(lead_id);
  create table if not exists caixa_eventos (id {ID}, provedor text not null, payload text not null, processado integer not null default 0, recebido_em text not null);
  `,
];

export async function migrar(db: Banco): Promise<void> {
  await db.todos("create table if not exists migracoes (versao integer primary key, aplicada_em text not null)");
  const feita = await um<{ v: number | null }>(db, "select max(versao) as v from migracoes");
  for (let versao = (feita?.v ?? 0) + 1; versao <= MIGRACOES.length; versao += 1) {
    const sql = MIGRACOES[versao - 1]!.replaceAll("{ID}", ID[db.dialeto]);
    for (const comando of sql.split(";").map((c) => c.trim()).filter(Boolean)) await db.todos(comando);
    // Duas máquinas migrando juntas: a segunda bate na chave e segue (o schema usa `if not exists`).
    await db.todos("insert into migracoes (versao, aplicada_em) values (?, ?) on conflict do nothing", [versao, agora()]);
  }
  // No Supabase, tabela sem RLS fica aberta para quem tiver a chave pública (anon) do projeto.
  // Com RLS ligado e nenhuma política, só o dono do banco (este programa) e a service role (a Edge
  // Function) acessam.
  if (db.dialeto === "postgres") {
    for (const tabela of TABELAS) await db.todos(`alter table ${tabela} enable row level security`);
  }
}

const TABELAS = ["migracoes", "operadores", "leads", "jobs", "acoes", "eventos", "estado", "uso_ia", "cache_ia", "mensagens", "caixa_eventos"];

export async function lerEstado<T>(db: Banco, chave: string): Promise<T | null> {
  const linha = await um<{ valor: string }>(db, "select valor from estado where chave = ?", [chave]);
  return linha ? (JSON.parse(linha.valor) as T) : null;
}

export async function gravarEstado(db: Banco, chave: string, valor: unknown): Promise<void> {
  await db.todos("insert into estado (chave, valor) values (?, ?) on conflict (chave) do update set valor = excluded.valor", [chave, JSON.stringify(valor)]);
}

export async function apagarEstado(db: Banco, chave: string): Promise<void> {
  await db.todos("delete from estado where chave = ?", [chave]);
}

export async function registrarEvento(db: Banco, operador: string | null, tipo: string, mensagem: string, leadId: number | null = null): Promise<void> {
  await db.todos("insert into eventos (operador, tipo, mensagem, lead_id, criado_em) values (?, ?, ?, ?, ?)", [operador, tipo, mensagem, leadId, agora()]);
}

/** Cada máquina se registra pelo @ do Instagram que usa. Mesmo @ em outra máquina é o mesmo operador. */
export async function registrarOperador(db: Banco, nome: string, instagram: string): Promise<void> {
  const t = agora();
  await db.todos("insert into operadores (nome, instagram, criado_em, visto_em) values (?, ?, ?, ?) on conflict (instagram) do update set nome = excluded.nome, visto_em = excluded.visto_em", [nome, instagram, t, t]);
}

export type Lead = {
  id: number;
  usuario: string;
  origem: string;
  estado: string;
  nome: string | null;
  bio: string | null;
  seguidores: number | null;
  seguindo: number | null;
  posts: number | null;
  link_externo: string | null;
  comercial: number | null;
  legendas: string | null;
  pontuacao: number | null;
  motivos: string | null;
  dono_de: number | null;
  abertura: string | null;
  seguimento: string | null;
  seguimentos: number;
  operador: string | null;
  contatado_em: string | null;
  ultimo_envio_em: string | null;
  respondeu_em: string | null;
};

export async function lerLead(db: Banco, id: number): Promise<Lead | undefined> {
  return await um<Lead>(db, "select * from leads where id = ?", [id]);
}

/** Cria o lead se o @ for novo. Devolve o id e se foi criado agora (o @ é único na base inteira). */
export async function criarLead(db: Banco, usuario: string, origem: string, extra: { dono_de?: number; estado?: string; pontuacao?: number | null } = {}): Promise<{ id: number; novo: boolean }> {
  const t = agora();
  const criado = await um<{ id: number }>(
    db,
    "insert into leads (usuario, origem, estado, dono_de, pontuacao, criado_em, atualizado_em) values (?, ?, ?, ?, ?, ?, ?) on conflict (usuario) do nothing returning id",
    [usuario, origem, extra.estado ?? "novo", extra.dono_de ?? null, extra.pontuacao ?? null, t, t],
  );
  if (criado) return { id: Number(criado.id), novo: true };
  const existente = await um<{ id: number }>(db, "select id from leads where usuario = ?", [usuario]);
  return { id: Number(existente!.id), novo: false };
}

/** Atualiza colunas do lead. Os nomes de coluna vêm do código, nunca de entrada externa. */
export async function atualizarLead(db: Banco, id: number, campos: Partial<Omit<Lead, "id">>): Promise<void> {
  const chaves = Object.keys(campos);
  if (chaves.length === 0) return;
  const sets = chaves.map((c) => `${c} = ?`).join(", ");
  await db.todos(`update leads set ${sets}, atualizado_em = ? where id = ?`, [...chaves.map((c) => (campos as Record<string, unknown>)[c] ?? null), agora(), id]);
}

/**
 * Reserva o lead para um envio: só um operador ganha, mesmo com várias máquinas na mesma base.
 * Devolve false se o lead já saiu do estado esperado (outro operador pegou, ou já foi enviado).
 */
export async function reservarLead(db: Banco, id: number, estadoEsperado: string, operador: string): Promise<boolean> {
  const linha = await um(db, "update leads set estado = 'enviando', operador = ?, atualizado_em = ? where id = ? and estado = ? and (operador is null or operador = ?) returning id", [operador, agora(), id, estadoEsperado, operador]);
  return linha !== undefined;
}
